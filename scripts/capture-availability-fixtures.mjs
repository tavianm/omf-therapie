#!/usr/bin/env node
/**
 * Golden availability fixtures — reproducible capture from the PRE-refactor
 * implementation (issue #153 / SC4 provenance, revue #154).
 *
 * The golden fixtures (tests/fixtures/availability/*.json) are the SC4
 * equivalence oracle: their `expected` games must provably come from the
 * pre-refactor derivation, not from the refactored implementation itself.
 * This script re-captures them from an immutable source revision:
 *
 *   1. `git archive <rev> src | tar -x` extracts the pre-refactor source
 *      tree into .tmp-fixture-capture/ (inside the repo, so vitest and the
 *      package graph resolve; the dir is outside the `tests/unit/**` include
 *      pattern and removed after the run).
 *   2. A generated THROWAWAY vitest file (tests/unit/zz-fixture-capture.replay.test.ts,
 *      deleted after the run) replays every fixture scenario through the OLD
 *      `getAvailableSlots` — the exact public API /api/availability called at
 *      that revision — with I/O mocked at the leaf boundaries and the clock
 *      frozen from the fixture inputs. The OLD module's own relative imports
 *      resolve inside the extracted tree (its only '@/...' imports are
 *      type-only and erased), so the derivation under replay is the
 *      pre-refactor code, not the current one.
 *   3. Regenerated games are diffed against the committed fixtures; with
 *      --write they overwrite them. Either way a provenance record is
 *      (re)written to tests/fixtures/availability/PROVENANCE.md.
 *
 * Usage:
 *   node scripts/capture-availability-fixtures.mjs [--rev <commit>] [--write]
 *
 * Default revision: 417309d — the commit that introduced the fixtures, whose
 * implementation predates the batch/derivation refactor (#153).
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TMP = resolve(REPO, '.tmp-fixture-capture');
const FIXTURE_DIR = resolve(REPO, 'tests/fixtures/availability');
const REPLAY_TEST = resolve(
  REPO,
  'tests/unit/zz-fixture-capture.replay.test.ts',
);
const RESULT_DIR = resolve(TMP, 'result');
const RESULT_FILE = resolve(RESULT_DIR, 'regenerated.json');

const args = process.argv.slice(2);
const revArgIdx = args.indexOf('--rev');
const REV = revArgIdx !== -1 ? args[revArgIdx + 1] : '417309d';
const WRITE = args.includes('--write');

function die(msg) {
  console.error(`[capture-availability-fixtures] ${msg}`);
  process.exit(1);
}

const REV_SHA = execFileSync('git', ['rev-parse', REV], {
  cwd: REPO,
  encoding: 'utf8',
}).trim();
console.log(`[capture-availability-fixtures] revision ${REV} → ${REV_SHA}`);

// --- 1. Extract the pre-refactor source tree ---------------------------------
rmSync(TMP, { recursive: true, force: true });
mkdirSync(RESULT_DIR, { recursive: true });
execFileSync(
  'bash',
  [
    '-c',
    `git -C ${JSON.stringify(REPO)} archive ${REV_SHA} src | tar -x -C ${JSON.stringify(TMP)}`,
  ],
  { stdio: 'inherit' },
);
if (!existsSync(resolve(TMP, 'src/lib/google-calendar.ts'))) {
  die(`revision ${REV} has no src/lib/google-calendar.ts — wrong tree?`);
}

// --- 2. Generate the throwaway replay test ------------------------------------
// Mocks are keyed by the RESOLVED module path, so mocking
// '../../.tmp-fixture-capture/src/lib/manual-slots.js' from the test file
// intercepts the OLD module's own './manual-slots.js' import (same file).
const RESULT_FILE_POSIX = JSON.stringify(RESULT_FILE).replace(/\\\\/g, '/');
const REPLAY_SOURCE = `// THROWAWAY — generated by scripts/capture-availability-fixtures.mjs.
// Replays the golden fixture scenarios through the PRE-REFACTOR
// implementation extracted at ${REV_SHA}. Deleted by the generator after the run.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname as pdirname, resolve as presolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, it, vi } from 'vitest';

const manualRows = vi.hoisted(() => ({
  fetchManualSlots: vi.fn(async () => []),
}));

vi.mock('../../.tmp-fixture-capture/src/lib/manual-slots.js', () => ({
  fetchManualSlots: manualRows.fetchManualSlots,
}));
vi.mock('../../.tmp-fixture-capture/src/lib/supabase.js', () => {
  const refuse = () => {
    throw new Error('supabase must not be reached in the replay');
  };
  return { supabaseAdmin: new Proxy({}, { get: refuse }), supabase: new Proxy({}, { get: refuse }) };
});
vi.mock('../../.tmp-fixture-capture/src/lib/resend.js', () => ({
  sendEmail: vi.fn(async () => {}),
}));
vi.mock('googleapis', () => ({
  google: {
    auth: { OAuth2: class {} },
    calendar: () => {
      throw new Error(
        'replay uses the options.calendar DI seam — the factory must not run',
      );
    },
  },
}));

import * as oldCalendar from '../../.tmp-fixture-capture/src/lib/google-calendar.js';

const FIXTURE_DIR = presolve(
  pdirname(fileURLToPath(import.meta.url)),
  '../fixtures/availability',
);
const NAMES = [
  'manual-slots-week',
  'partial-busy-overlaps',
  'dst-transition-week',
  'mock-mode',
];
const GAMES = [
  { key: 'in-person/60', duration: 60, mode: 'in-person' },
  { key: 'in-person/90', duration: 90, mode: 'in-person' },
  { key: 'video/60', duration: 60, mode: 'video' },
  { key: 'video/90', duration: 90, mode: 'video' },
];

it('replays every scenario through the pre-refactor implementation', async () => {
  expect(typeof oldCalendar.getAvailableSlots).toBe('function');

  const regenerated = {};
  for (const name of NAMES) {
    const fixture = JSON.parse(
      readFileSync(presolve(FIXTURE_DIR, name + '.json'), 'utf8'),
    );
    const inputs = fixture.inputs;
    vi.stubEnv('DEV', inputs.mockMode);
    vi.stubEnv('GOOGLE_CALENDAR_MOCK', inputs.mockMode ? 'true' : 'false');
    vi.stubEnv('GOOGLE_CALENDAR_ID', inputs.calendarId);
    vi.useFakeTimers({ toFake: ['Date'] });
    vi.setSystemTime(new Date(inputs.frozenNow));
    manualRows.fetchManualSlots.mockReset();
    manualRows.fetchManualSlots.mockResolvedValue(
      inputs.manualSlotRows.map(r => ({ ...r })),
    );

    const fakeCalendar = {
      freebusy: {
        query: async () => ({
          data: {
            calendars: {
              [inputs.calendarId]: {
                busy: inputs.freebusyBusyPeriods.map(b => ({ ...b })),
              },
            },
          },
        }),
      },
    };

    const games = {};
    for (const game of GAMES) {
      games[game.key] = await oldCalendar.getAvailableSlots(
        new Date(inputs.range.start),
        new Date(inputs.range.end),
        game.duration,
        game.mode,
        inputs.dbBusyPeriods,
        inputs.mockMode
          ? {}
          : { calendarId: inputs.calendarId, calendar: fakeCalendar },
      );
    }
    regenerated[name] = {
      scenario: fixture.scenario,
      description: fixture.description,
      inputs: fixture.inputs,
      expected: games,
    };
    vi.useRealTimers();
    vi.unstubAllEnvs();
  }
  writeFileSync(${RESULT_FILE_POSIX}, JSON.stringify(regenerated, null, 2));
});
`;

writeFileSync(REPLAY_TEST, REPLAY_SOURCE);

// --- 3. Run the replay ----------------------------------------------------------
try {
  execFileSync(
    process.execPath,
    [
      'node_modules/vitest/vitest.mjs',
      'run',
      'tests/unit/zz-fixture-capture.replay.test.ts',
      '--maxWorkers=1',
    ],
    { cwd: REPO, stdio: 'inherit' },
  );
} finally {
  rmSync(REPLAY_TEST, { force: true });
}

// --- 4. Diff regenerated vs committed, optionally write --------------------------
if (!existsSync(RESULT_FILE)) {
  die('replay produced no output — see the vitest run above');
}
const regenerated = JSON.parse(readFileSync(RESULT_FILE, 'utf8'));

const report = [];
let identical = true;
for (const name of Object.keys(regenerated)) {
  const committed = JSON.parse(
    readFileSync(resolve(FIXTURE_DIR, `${name}.json`), 'utf8'),
  );
  const same =
    JSON.stringify(committed.expected) ===
    JSON.stringify(regenerated[name].expected);
  identical = identical && same;
  report.push({ fixture: `${name}.json`, identicalToCommitted: same });
  if (!same && WRITE) {
    writeFileSync(
      resolve(FIXTURE_DIR, `${name}.json`),
      `${JSON.stringify(regenerated[name], null, 2)}\n`,
    );
    console.log(`[capture-availability-fixtures] OVERWROTE ${name}.json`);
  }
}

// --- 5. Provenance record ----------------------------------------------------------
function sha256(file) {
  return createHash('sha256').update(readFileSync(file)).digest('hex');
}
const provenanceSha = {};
for (const name of Object.keys(regenerated)) {
  provenanceSha[`${name}.json`] = sha256(
    resolve(FIXTURE_DIR, `${name}.json`),
  );
}
const capturedAt = new Date().toISOString();
const provenance = `# Availability golden fixtures — provenance (SC4)

The \`expected\` games in \`*.json\` are captured from the PRE-refactor
availability implementation. This record pins the exact source revision and
the reproducible capture command so the oracle's origin is verifiable —
regenerating from the refactored implementation would be circular and is NOT
what this records.

- **Source revision:** \`${REV}\` (\`${REV_SHA}\`) — pre-refactor
  \`getAvailableSlots\` (the commit that introduced these fixtures; the batch
  / derivation refactor of #153 landed strictly after it).
- **Capture command:** \`node scripts/capture-availability-fixtures.mjs --rev ${REV}${
    WRITE ? ' --write' : ''
  }\`
- **Last verified:** ${capturedAt}
- **Result:** ${
    identical
      ? 'regenerated games are IDENTICAL to the committed fixtures (bit-for-bit expected blocks) — provenance confirmed.'
      : WRITE
        ? 'regenerated games DIFFERED from the committed fixtures — the fixtures were overwritten with the pre-refactor output via --write.'
        : 'regenerated games DIFFER from the committed fixtures — rerun with --write to re-pin them on the pre-refactor output.'
  }

## Fixture digests (post-run)

| Fixture | sha256 |
|---------|--------|
${Object.entries(provenanceSha)
  .map(([f, h]) => `| \`${f}\` | \`${h}\` |`)
  .join('\n')}
`;
writeFileSync(resolve(FIXTURE_DIR, 'PROVENANCE.md'), provenance);

// --- 6. Cleanup -----------------------------------------------------------------------
rmSync(TMP, { recursive: true, force: true });

console.log('\n[capture-availability-fixtures] summary:');
for (const row of report) {
  console.log(
    `  ${row.identicalToCommitted ? 'identical' : 'DIFFERS '}  ${row.fixture}`,
  );
}
console.log(
  `[capture-availability-fixtures] overall: ${identical ? 'IDENTICAL' : 'DIFFERS'}${WRITE ? ' (--write applied)' : ''}`,
);
if (!identical && !WRITE) {
  process.exitCode = 2;
}
